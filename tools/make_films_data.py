#!/usr/bin/env python3
"""Write site/data/films.js from the curated tools/films_seed.json.

  python3 tools/make_films_data.py

The seed is the source, edited by hand through tools/films_batch.py; this file is generated, so never edit
site/data/films.js directly. The wall loads it only when someone first opens Documentaries, the way it loads
the books, so the buildings wall never waits for it.

Until the owner adds a TMDB key there are no posters, scores or streaming services. Each film therefore carries
`find`: four plain links a student can follow themselves (JustWatch, IMDb, Letterboxd, and a trailer search).
When TMDB data arrives, `watch` fills and the page shows services instead, the same slot either way.
"""
import json, re, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED = ROOT / 'tools' / 'films_seed.json'
OUT = ROOT / 'site' / 'data' / 'films.js'


def slug(s):
    s = unicodedata.normalize('NFKD', s or '').encode('ascii', 'ignore').decode().lower()
    return re.sub(r'-+', '-', re.sub(r'[^a-z0-9]+', '-', s)).strip('-')[:70]


def find_links(f):
    """Plain links to the places a student can look the film up, for as long as there is no streaming data."""
    q = f['title'] + (f' {f["y"]}' if f.get('y') else '')
    imdb = f'https://www.imdb.com/title/{f["imdb"]}/' if f.get('imdb') else 'https://www.imdb.com/find/?q=' + quote(q)
    # Each link says what it gives you, rather than four rows all reading the same.
    return [['Where to stream', 'JustWatch', 'https://www.justwatch.com/us/search?q=' + quote(f['title'])],
            ['Cast and crew', 'IMDb', imdb],
            ['Reviews', 'Letterboxd', 'https://letterboxd.com/search/' + quote(q) + '/'],
            ['Trailer', 'YouTube', 'https://www.youtube.com/results?search_query=' + quote(q + ' trailer')]]


def quote(s):
    import urllib.parse
    return urllib.parse.quote(s)


def main():
    seed = json.loads(SEED.read_text())
    seen, out = set(), []
    for f in seed:
        s = slug(f['title'])
        while s in seen:
            s += '-2'
        seen.add(s)
        film = {'id': f['id'], 'slug': s, 'title': f['title'], 'year': f.get('year') or '', 'y': f.get('y') or 0,
                'kind': f.get('kind'), 'genres': f.get('genres') or [], 'summary': f.get('summary'),
                'architects': (f.get('about') or {}).get('architects') or [],
                'buildings': (f.get('about') or {}).get('buildings') or [],
                'sources': f.get('sources') or [], 'find': find_links(f)}
        for k in ('director', 'runtime_min', 'language', 'topics', 'movements', 'featured',
                  'ratings', 'watch', 'trailer', 'image', 'imdb', 'letterboxd', 'tmdb', 'qid'):
            if f.get(k):
                film[k] = f[k]
        out.append(film)
    out.sort(key=lambda f: (-f['y'], f['title']))
    OUT.write_text('// Architecture documentaries, curated in tools/films_seed.json. Generated by '
                   'tools/make_films_data.py: edit the seed, not this file.\n'
                   'window.FILMS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
    size = OUT.stat().st_size
    linked = sum(1 for f in out if f['architects'] or f['buildings'])
    print(f'{len(out)} films -> site/data/films.js ({size / 1024:.0f} KB); {linked} reach the wall; '
          f'{sum(1 for f in out if f.get("watch"))} with streaming data')


if __name__ == '__main__':
    main()
